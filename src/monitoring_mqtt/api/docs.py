"""API reference page (Scalar) and the OpenAPI document.

``/docs`` serves a Scalar API reference built from ``/openapi.json``. The event payloads
carried by the ingest batches (`Measurement`, `AlertEvent`) are added to the OpenAPI
components so the reference documents them too.

The versioned copies in ``docs/`` are generated without a database::

    python -m monitoring_mqtt.api.docs > docs/openapi.json
    python -m monitoring_mqtt.api.docs --html > docs/api-reference.html   # stand-alone page
"""

from __future__ import annotations

import json
import sys
from typing import Any

from fastapi import FastAPI
from fastapi.openapi.utils import get_openapi
from fastapi.responses import HTMLResponse

from monitoring_mqtt.core.alerts import AlertEvent
from monitoring_mqtt.core.models import Measurement

# Pinned: the page must not change when a new Scalar version is published.
SCALAR_SCRIPT = "https://cdn.jsdelivr.net/npm/@scalar/api-reference@1.76.0"

EVENT_SCHEMAS: dict[str, type] = {"Measurement": Measurement, "AlertEvent": AlertEvent}

PAGE = """<!doctype html>
<html lang="en">
  <head>
    <title>{title}</title>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
  </head>
  <body>
    <script id="api-reference" data-url="{openapi_url}"></script>
    <script src="{script}"></script>
  </body>
</html>
"""


STANDALONE_PAGE = """<!doctype html>
<html lang="en">
  <head>
    <title>{title}</title>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
  </head>
  <body>
    <!-- Generated by `python -m monitoring_mqtt.api.docs --html`; do not edit. -->
    <script id="api-reference" type="application/json">
{document}
    </script>
    <script src="{script}"></script>
  </body>
</html>
"""


def scalar_page(title: str, openapi_url: str) -> str:
    return PAGE.format(title=title, openapi_url=openapi_url, script=SCALAR_SCRIPT)


def standalone_page(title: str, document: dict[str, Any]) -> str:
    """A reference page with the OpenAPI document inside: opens without the API running."""
    content = json.dumps(document, indent=2, ensure_ascii=False).replace("</", "<\\/")
    return STANDALONE_PAGE.format(title=title, document=content, script=SCALAR_SCRIPT)


def build_openapi(app: FastAPI) -> dict[str, Any]:
    if app.openapi_schema:
        return app.openapi_schema
    schema = get_openapi(
        title=app.title,
        version=app.version,
        description=app.description,
        routes=app.routes,
        tags=app.openapi_tags,
    )
    components = schema.setdefault("components", {}).setdefault("schemas", {})
    for name, model in EVENT_SCHEMAS.items():
        model_schema = model.model_json_schema(ref_template="#/components/schemas/{model}")
        components.update(model_schema.pop("$defs", {}))
        components[name] = model_schema
    app.openapi_schema = schema
    return schema


def install(app: FastAPI) -> None:
    app.openapi = lambda: build_openapi(app)  # type: ignore[method-assign]

    @app.get("/docs", include_in_schema=False)
    def reference() -> HTMLResponse:
        return HTMLResponse(scalar_page(f"{app.title} API reference", app.openapi_url or ""))


def main() -> int:
    from monitoring_mqtt.api.app import create_app

    app = create_app(store=_NoStore())
    if "--html" in sys.argv[1:]:
        sys.stdout.write(standalone_page(f"{app.title} API reference", app.openapi()))
    else:
        sys.stdout.write(json.dumps(app.openapi(), indent=2, ensure_ascii=False) + "\n")
    return 0


class _NoStore:
    """Building the document needs no database."""


if __name__ == "__main__":
    sys.exit(main())
